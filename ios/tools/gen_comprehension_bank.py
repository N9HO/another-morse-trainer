#!/usr/bin/env python3
"""Write each tree's own copy of the Daily Comprehension bank (#353).

Source of truth: fixtures/comprehension-bank.json (data, shared by all three
trees). Output: one generated source table per tree, in that tree's own idiom,
so no tree reads another tree's directory and none reads fixtures/ at run time:

  ios/Sources/MorseKit/ComprehensionBank.swift
  android/app/src/main/java/app/anothermorsetrainer/morsekit/ComprehensionBank.kt
  desktop/app/src/main/kotlin/app/anothermorsetrainer/morsekit/ComprehensionBank.kt

A test in each tree asserts its table equals the fixture, so editing the
fixture without re-running this (or the reverse) fails CI. Item ORDER is part
of day selection (docs/daily-comprehension-design.md): treat any change to
existing items as a deliberate, announced change.

Usage (from the repo root): python3 ios/tools/gen_comprehension_bank.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
items = json.loads((root / "fixtures/comprehension-bank.json").read_text())["items"]

def q(s):
    return json.dumps(s, ensure_ascii=False)

HEADER = ("Daily Comprehension question bank (#353). Auto-generated by\n"
          "tools/gen_comprehension_bank.py from fixtures/comprehension-bank.json; do not\n"
          "hand-edit. Order is part of day selection.")

swift = ["import Foundation", ""]
swift += ["// " + l for l in HEADER.splitlines()]
swift += ["", "extension ComprehensionBank {", "    public static let items: [ComprehensionItem] = ["]
for it in items:
    swift.append("        ComprehensionItem(id: %s, sentence: %s, question: %s, answer: %s, distractors: [%s], kochLevel: %d),"
                 % (q(it["id"]), q(it["sentence"]), q(it["question"]), q(it["answer"]),
                    ", ".join(q(d) for d in it["distractors"]), it["kochLevel"]))
swift += ["    ]", "}", ""]
(root / "ios/Sources/MorseKit/ComprehensionBank.swift").write_text("\n".join(swift))

kt = ["package app.anothermorsetrainer.morsekit", ""]
kt += ["// " + l for l in HEADER.splitlines()]
kt += ["", "internal val comprehensionBankItems: List<ComprehensionItem> = listOf("]
for it in items:
    kt.append("    ComprehensionItem(%s, %s, %s, %s, listOf(%s), %d),"
              % (q(it["id"]), q(it["sentence"]), q(it["question"]), q(it["answer"]),
                 ", ".join(q(d) for d in it["distractors"]), it["kochLevel"]))
kt += [")", ""]
for p in ("android/app/src/main/java/app/anothermorsetrainer/morsekit/ComprehensionBank.kt",
          "desktop/app/src/main/kotlin/app/anothermorsetrainer/morsekit/ComprehensionBank.kt"):
    (root / p).write_text("\n".join(kt))
print(len(items), "items written")
